/**
 * Regenerates docs/IMAGE_ASSETS.md from the media manifest (seed/media.ts),
 * so the asset register can never drift from what the site actually ships.
 *
 *   npm run docs:images
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { MEDIA, type MediaSeed } from "../seed/media";

const dimensions: Record<string, { width: number; height: number; bytes: number }> = existsSync("seed/data/image-dimensions.json")
  ? JSON.parse(readFileSync("seed/data/image-dimensions.json", "utf8"))
  : {};

const TYPE: Record<MediaSeed["source"], string> = { bca: "Original (BCA)", stock: "Stock", ai: "AI-generated" };
const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

function table(items: MediaSeed[]) {
  const rows = items.map((item) => {
    const d = dimensions[item.url];
    const size = d ? `${d.width} x ${d.height}, ${Math.max(1, Math.round(d.bytes / 1024))} KB` : "";
    const source = item.sourceUrl ? `[source](${item.sourceUrl})` : (item.credit ?? "");
    return `| \`${item.url.replace("/images/", "")}\` | ${TYPE[item.source]} | ${size} | ${cell(item.alt)} | ${cell(item.usedOn)} | ${cell(item.licence)} | ${source} |`;
  });
  return ["| File (under `public/images/`) | Type | Size | Alt text | Used on | Licence or usage status | Source |", "|---|---|---|---|---|---|---|", ...rows].join("\n");
}

const groups: [string, string, (item: MediaSeed) => boolean][] = [
  ["Brand", "The official BCA logo and the butterfly mark taken from it.", (i) => i.key.startsWith("brand.")],
  ["ICF accreditation marks", "As displayed on the existing BCA website. Only Level 1 and Level 2 are shown on the new site.", (i) => i.key.startsWith("icf.")],
  ["Client logos", "Third-party trademarks shown on the existing BCA website.", (i) => i.key.startsWith("logo.")],
  ["People", "Authentic photographs of real people. Never replaced with generated imagery.", (i) => i.key.startsWith("person.")],
  ["Event photographs", "Authentic photographs from BCA workshops and events.", (i) => i.key.startsWith("gallery.")],
  ["Editorial photography (AI-generated)", "Created with Higgsfield for this project. Prompts are in HIGGSFIELD_IMAGE_PROMPTS.md.", (i) => i.source === "ai"],
];

const counts = { bca: MEDIA.filter((m) => m.source === "bca").length, ai: MEDIA.filter((m) => m.source === "ai").length, stock: MEDIA.filter((m) => m.source === "stock").length };
const totalKb = Math.round(Object.values(dimensions).reduce((sum, d) => sum + d.bytes, 0) / 1024);

const doc = `# Image assets

<!-- Generated by \`npm run docs:images\` from seed/media.ts. Edit the manifest, not this file. -->

Every image the site ships with, where it came from, how it may be used and where it appears.

- **${MEDIA.length} assets**: ${counts.bca} authentic BCA assets, ${counts.ai} AI-generated, ${counts.stock} stock.
- **Total weight of the masters: ${totalKb.toLocaleString("en-GB")} KB.** Visitors never download a master: \`next/image\` serves AVIF or WebP at the size their screen needs.
- All files are hosted locally under \`public/images/\`. Nothing is hot-linked from a third-party site.
- No stock photography was needed. If stock is added later, record it in \`seed/media.ts\` (or set "Where it came from" to "Licensed stock" in the Media library) with the source link and licence.

## Rules this project follows

1. Real people are shown only in authentic photographs. No image presents a generated person as a founder, faculty member, student or client.
2. No image contains text that needs to be read. Headings, labels and buttons are real HTML.
3. Every image has meaningful alt text, stored once in the Media library and reused wherever the image appears.
4. Each image has a focal point, so crops on every screen size keep the subject in view.
5. The legacy site's blog images and page illustrations were **not** reused, because their licences could not be established.

## Before launch

- [ ] Owner confirms BCA holds the rights to each authentic photograph and that the people pictured have consented.
- [ ] Owner confirms permission to display each client logo.
- [ ] Owner confirms current ICF accreditation for each level before its mark is shown (see CONTENT_APPROVAL_CHECKLIST.md).
- [ ] Owner approves the navy-wordmark logo variant used on light backgrounds.
- [ ] Owner reviews the AI-generated photography and is comfortable with its use. Consider adding a short note to the site footer or privacy policy if your audience would expect disclosure.

${groups.map(([title, intro, filter]) => `## ${title}\n\n${intro}\n\n${table(MEDIA.filter(filter))}`).join("\n\n")}

## Replacing an image

Open **Admin > Media library**, select the image and choose **Replace file**. Every page that uses it updates automatically, with no change to the page itself. To use a different image in one place only, edit that page or programme and choose another image from the library.
`;

writeFileSync("docs/IMAGE_ASSETS.md", doc);
console.log(`docs/IMAGE_ASSETS.md written (${MEDIA.length} assets)`);
